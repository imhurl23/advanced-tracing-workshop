"""Curate a Pattern's evidence from the shared seed into a dataset in YOUR project (PARTICIPANT.md step 7).

READ: the Pattern (by stable ID) from **super-stonks** — `bt sql` over `project_patterns()`.
      Its evidence carries an `affected_filter` (the BTQL that selects the failing spans);
      we run that over the project logs to collect every affected turn, not just the
      handful of sample traces the Pattern links to.
WRITE: a dataset in your own **BRAINTRUST_DEFAULT_PROJECT** with `bt datasets create`
       (or `update` if it exists). One row per failing turn: input = the user's question,
       metadata = the broken reply, the failing tool call, and the source trace.

    make curate-dataset
    PATTERN="Dotted tickers fail or change share classes" DATASET=share-class-tickers make curate-dataset
"""

from __future__ import annotations

import json
import os
import subprocess
import tempfile

SHARED_PROJECT = os.environ.get("PATTERN_PROJECT", "super-stonks")
# Titles are generated by Patterns and can change. Pin the shared workshop record;
# an explicit PATTERN name override remains useful for a different seed/project.
WORKSHOP_PATTERN_ID = "b2c6500a-00ec-480f-a5ce-ed9456b6bd76"
PATTERN = os.environ.get("PATTERN")  # optional case-insensitive name substring
PATTERN_ID = os.environ.get("PATTERN_ID")
DATASET = os.environ.get("DATASET", "share-class-tickers")


def _bt_json(args: list[str]):
    out = subprocess.run(["bt", *args], capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def _sql(query: str) -> list[dict]:
    # bt sql returns 10 rows unless a LIMIT is given, and the linter caps queries that
    # select input/output at 100.
    return _bt_json(["sql", f"{query} LIMIT 100", "--json"]).get("data") or []


def _quote(values) -> str:
    return ", ".join("'" + str(v).replace("'", "''") + "'" for v in values)


def _shared_project_id() -> str:
    for p in _bt_json(["projects", "list", "--json"]):
        if p["name"] == SHARED_PROJECT:
            return p["id"]
    raise SystemExit(f"project '{SHARED_PROJECT}' not found")


def _pattern(pid: str) -> dict:
    rows = _sql(
        f"SELECT id, name, status, evidence FROM project_patterns('{pid}') "
        f"WHERE created >= '2020-01-01'"
    )
    pattern_id = PATTERN_ID or (WORKSHOP_PATTERN_ID if not PATTERN else None)
    if pattern_id:
        matches = [r for r in rows if r["id"] == pattern_id]
        selector = f"ID '{pattern_id}'"
    else:
        matches = [r for r in rows if PATTERN.lower() in (r.get("name") or "").lower()]
        selector = f"name containing '{PATTERN}'"
    active = [r for r in matches if r.get("status") == "active"] or matches
    if not active:
        names = "\n  ".join(sorted(f"{r['id']}  {r.get('name') or ''}" for r in rows))
        raise SystemExit(
            f"no pattern matching {selector} in {SHARED_PROJECT}. Patterns:\n  {names}\n"
            "Set PATTERN_ID to an ID above, or PATTERN to a unique name substring."
        )
    if len(active) > 1:
        names = "\n  ".join(f"{r['id']}  {r['name']}" for r in active)
        raise SystemExit(f"multiple patterns matching {selector}:\n  {names}\nSet PATTERN_ID explicitly.")
    return active[0]


def _failing_tool_spans(pid: str, evidence: dict) -> list[dict]:
    freq = evidence.get("frequency") or {}
    flt = freq.get("affected_filter")
    since = ((freq.get("snapshot") or {}).get("time_window") or {}).get("from") or "2020-01-01"
    if flt:
        return _sql(
            f"SELECT root_span_id, span_parents, span_attributes.name AS tool, input, output "
            f"FROM project_logs('{pid}') WHERE created >= '{since}' AND ({flt})"
        )
    # No frequency filter on this Pattern — fall back to its sample traces' tool errors.
    roots = evidence.get("root_span_ids") or []
    if not roots:
        return []
    return _sql(
        f"SELECT root_span_id, span_parents, span_attributes.name AS tool, input, output "
        f"FROM project_logs('{pid}') WHERE root_span_id IN ({_quote(roots)}) "
        f"AND span_attributes.type = 'tool' AND output.error IS NOT NULL"
    )


def _turns(pid: str, span_ids: list[str], root_ids: list[str]) -> dict[str, dict]:
    # The SQL linter requires a root_span_id filter alongside span_id.
    rows = _sql(
        f"SELECT span_id, span_attributes.name AS name, input, output FROM project_logs('{pid}') "
        f"WHERE root_span_id IN ({_quote(root_ids)}) AND span_id IN ({_quote(span_ids)})"
    )
    return {r["span_id"]: r for r in rows if str(r.get("name", "")).startswith("turn_")}


def _write_dataset(project: str, rows: list[dict], description: str) -> None:
    with tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False) as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")
        path = f.name
    existing = {d.get("name") for d in _bt_json(["datasets", "list", "--json", "-p", project])}
    if DATASET in existing:
        cmd = ["datasets", "update", DATASET, "--file", path, "-p", project]
    else:
        cmd = ["datasets", "create", DATASET, "--description", description, "--file", path, "-p", project]
    subprocess.run(["bt", *cmd], check=True)
    os.unlink(path)


def main() -> None:
    project = os.environ["BRAINTRUST_DEFAULT_PROJECT"]  # write target = your project
    if project == SHARED_PROJECT:
        raise SystemExit(f"refusing to write the dataset into the shared '{SHARED_PROJECT}' project")
    pid = _shared_project_id()
    pattern = _pattern(pid)
    evidence = pattern.get("evidence") or {}
    tool_spans = _failing_tool_spans(pid, evidence)
    parents = {s["span_parents"][0]: s for s in tool_spans if s.get("span_parents")}
    roots = sorted({s["root_span_id"] for s in tool_spans})
    turns = _turns(pid, list(parents), roots) if parents else {}
    print(f"[curate] pattern '{pattern['name']}': {len(tool_spans)} failing tool calls "
          f"in {len(turns)} turns → dataset '{DATASET}' in '{project}'")

    rows = []
    for span_id, turn in turns.items():
        tool = parents[span_id]
        rows.append({
            "id": span_id,  # stable → re-running upserts
            "input": turn.get("input"),
            "expected": None,
            "metadata": {
                "broken_output": turn.get("output"),
                "failure_category": pattern["name"],
                "failed_tool": tool.get("tool"),
                "tool_input": tool.get("input"),
                "tool_output": tool.get("output"),
                "pattern_id": pattern["id"],
                "source_project": SHARED_PROJECT,
                "source_span_name": turn.get("name"),
                "source_trace_id": tool.get("root_span_id"),
            },
        })
    if not rows:
        raise SystemExit("no affected turns found — has the Pattern's window gone stale? Top up the seed.")
    _write_dataset(project, rows, f"Failing turns from the '{pattern['name']}' Pattern in {SHARED_PROJECT}.")
    print(f"[curate] wrote {len(rows)} rows to {project}/{DATASET}")


if __name__ == "__main__":
    main()
